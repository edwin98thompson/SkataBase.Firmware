#pragma once

#include <stdint.h>

enum CommandId : uint8_t
{
    // Commands sent from the client to the device.
    CMD_NONE = 0,
    CMD_START_MAGNETOMETER_CALIBRATION = 1,
    CMD_START_ACCELEROMETER_CALIBRATION = 2,
    CMD_START_GYROSCOPE_CALIBRATION = 3,
    CMD_RESET_MAGNETOMETER_CALIBRATION = 4,
    CMD_RESET_ACCELEROMETER_CALIBRATION = 5,
    CMD_RESET_GYROSCOPE_CALIBRATION = 6,
    CMD_ENABLE_MAGNETOMETER_CALIBRATION = 7,
    CMD_DISABLE_MAGNETOMETER_CALIBRATION = 8,
    CMD_ENABLE_ACCELEROMETER_CALIBRATION = 9,
    CMD_DISABLE_ACCELEROMETER_CALIBRATION = 10,
    CMD_ENABLE_GYROSCOPE_CALIBRATION = 11,
    CMD_DISABLE_GYROSCOPE_CALIBRATION = 12,
    CMD_SET_BETA_VALUE = 13
};

struct CommandPacket
{
    uint8_t protocolVersion = 1;
    CommandId commandId = CMD_NONE;
    float betaValue = 0.0f;
};
